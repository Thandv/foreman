/**
 * Which tests a diff adds or changes, read off the source of one JS/TS test
 * file at the base and in the reviewed tree. No module is loaded and nothing
 * is run: a small scanner skips strings, comments, template literals and regex
 * literals, and finds the node:test calls — `test(`, `it(`, `describe(`,
 * `suite(` (with `.skip`/`.only`/`.todo`) and a subtest's `t.test(` — with
 * their first argument and the source they span.
 *
 * A test is CHANGED when a changed line of its file falls in its own lines (its
 * call, less the calls nested in it), in the own lines of a describe around it,
 * or in a loop between it and its parent that it is generated by (a table of
 * cases). A renamed test changed its first line, so it counts. Changed lines in
 * no test at all (imports, helpers, fixtures) are counted, not attributed: no
 * call graph is built.
 *
 * Each call carries the line and columns V8 reports a test at (the `location`
 * of a TAP result), so the caller can match a run's results to these calls
 * whatever names a loop or a variable gave them.
 */

export interface TestCall {
  kind: 'test' | 'suite';
  /** The callee as written: `test`, `it.skip`, `t.test`, `describe`. */
  callee: string;
  /** 1-based line of the callee, and the 1-based column of each identifier in it (V8 reports a call at its last). */
  line: number;
  cols: number[];
  /** Last line of the call (its closing parenthesis). */
  endLine: number;
  /** The first argument's source text; '' when there is none. */
  nameSrc: string;
  /** The name when the first argument is a literal; null when it is built at run time. */
  name: string | null;
  /** A regex source (no anchors) matching every name the first argument can give; null when that cannot be said. */
  namePattern: string | null;
  /** Index of the enclosing test or describe call in the list, or null at the top level. */
  parent: number | null;
  /** The source of the call after its first argument: what a rename leaves alone. */
  body: string;
  /** The innermost loop between this call and its parent that it is inside, as lines; null when there is none. */
  loop: { startLine: number; endLine: number } | null;
  start: number;
  end: number;
}

type Tok =
  | { t: 'id'; v: string; s: number; e: number }
  | { t: 'p'; v: string; s: number; e: number }
  | { t: 'str'; v: string; s: number; e: number }
  | { t: 'tpl'; parts: string[]; s: number; e: number }
  | { t: 'other'; s: number; e: number };

const REGEX_AFTER_WORD = new Set(['return', 'typeof', 'case', 'do', 'else', 'in', 'of', 'new', 'delete', 'void', 'throw', 'instanceof', 'yield', 'await']);
const REGEX_AFTER_PUNCT = new Set(['(', ',', '=', ':', '[', '!', '&', '|', '?', '{', '}', ';', '+', '-', '*', '%', '<', '>', '~', '^']);

function unescapeJs(raw: string): string {
  return raw.replace(/\\(u\{[0-9a-fA-F]+\}|u[0-9a-fA-F]{4}|x[0-9a-fA-F]{2}|\r\n|[\s\S])/g, (_all, esc: string) => {
    if (esc.startsWith('u{')) return String.fromCodePoint(parseInt(esc.slice(2, -1), 16));
    if (esc.length === 5 && esc[0] === 'u') return String.fromCharCode(parseInt(esc.slice(1), 16));
    if (esc.length === 3 && esc[0] === 'x') return String.fromCharCode(parseInt(esc.slice(1), 16));
    switch (esc) {
      case 'n': return '\n';
      case 't': return '\t';
      case 'r': return '\r';
      case 'b': return '\b';
      case 'f': return '\f';
      case 'v': return '\v';
      case '0': return '\0';
      case '\n': case '\r\n': case '\r': return '';
      default: return esc;
    }
  });
}

/** Tokens of `src`: identifiers, punctuation and literals. Anything inside a template's `${}` is skipped, not read. */
function tokenize(src: string): Tok[] {
  const out: Tok[] = [];
  let i = 0;
  const n = src.length;
  const lastSig = (): Tok | undefined => out[out.length - 1];
  /** End of a template literal opening at `from` (the backtick), and its literal parts. */
  const template = (from: number): { end: number; parts: string[] } => {
    const parts: string[] = [];
    let j = from + 1;
    let part = '';
    while (j < n) {
      const c = src[j]!;
      if (c === '\\') { part += src.slice(j, j + 2); j += 2; continue; }
      if (c === '`') { parts.push(part); return { end: j + 1, parts }; }
      if (c === '$' && src[j + 1] === '{') {
        parts.push(part);
        part = '';
        j = skipCode(j + 2, '}');
        continue;
      }
      part += c;
      j++;
    }
    parts.push(part);
    return { end: n, parts };
  };
  /** Skip code from `from` to the matching `close`; returns the index after it. */
  const skipCode = (from: number, close: string): number => {
    let depth = 0;
    let j = from;
    while (j < n) {
      const c = src[j]!;
      if (c === '/' && src[j + 1] === '/') { const nl = src.indexOf('\n', j); j = nl < 0 ? n : nl; continue; }
      if (c === '/' && src[j + 1] === '*') { const e = src.indexOf('*/', j + 2); j = e < 0 ? n : e + 2; continue; }
      if (c === '"' || c === "'") { j = stringEnd(j); continue; }
      if (c === '`') { j = template(j).end; continue; }
      if (c === '{') depth++;
      else if (c === '}') {
        if (depth === 0 && close === '}') return j + 1;
        depth--;
      }
      j++;
    }
    return n;
  };
  const stringEnd = (from: number): number => {
    const q = src[from];
    let j = from + 1;
    while (j < n && src[j] !== q && src[j] !== '\n') j += src[j] === '\\' ? 2 : 1;
    return Math.min(n, j + 1);
  };
  while (i < n) {
    const c = src[i]!;
    if (/\s/.test(c)) { i++; continue; }
    if (c === '/' && src[i + 1] === '/') { const nl = src.indexOf('\n', i); i = nl < 0 ? n : nl; continue; }
    if (c === '/' && src[i + 1] === '*') { const e = src.indexOf('*/', i + 2); i = e < 0 ? n : e + 2; continue; }
    if (c === '"' || c === "'") {
      const e = stringEnd(i);
      out.push({ t: 'str', v: unescapeJs(src.slice(i + 1, e - 1)), s: i, e });
      i = e;
      continue;
    }
    if (c === '`') {
      const { end, parts } = template(i);
      out.push({ t: 'tpl', parts: parts.map(unescapeJs), s: i, e: end });
      i = end;
      continue;
    }
    if (/[A-Za-z_$]/.test(c)) {
      let j = i + 1;
      while (j < n && /[\w$]/.test(src[j]!)) j++;
      out.push({ t: 'id', v: src.slice(i, j), s: i, e: j });
      i = j;
      continue;
    }
    if (/[0-9]/.test(c)) {
      let j = i + 1;
      while (j < n && /[\w.]/.test(src[j]!)) j++;
      out.push({ t: 'other', s: i, e: j });
      i = j;
      continue;
    }
    if (c === '/') {
      const prev = lastSig();
      const regex = !prev
        || (prev.t === 'p' && REGEX_AFTER_PUNCT.has(prev.v))
        || (prev.t === 'id' && REGEX_AFTER_WORD.has(prev.v));
      if (regex) {
        let j = i + 1;
        let cls = false;
        while (j < n && src[j] !== '\n') {
          const d = src[j]!;
          if (d === '\\') { j += 2; continue; }
          if (d === '[') cls = true;
          else if (d === ']') cls = false;
          else if (d === '/' && !cls) break;
          j++;
        }
        j++;
        while (j < n && /[a-z]/i.test(src[j]!)) j++;
        out.push({ t: 'other', s: i, e: j });
        i = j;
        continue;
      }
    }
    // `?.` is a member access like `.`; a lone `.` too. Everything else is one character of punctuation.
    if (c === '?' && src[i + 1] === '.' && !/[0-9]/.test(src[i + 2] ?? '')) {
      out.push({ t: 'p', v: '.', s: i, e: i + 2 });
      i += 2;
      continue;
    }
    out.push({ t: 'p', v: c, s: i, e: i + 1 });
    i++;
  }
  return out;
}

const BASE_TEST = new Set(['test', 'it']);
const BASE_SUITE = new Set(['describe', 'suite']);
const MODIFIERS = new Set(['skip', 'only', 'todo']);

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
}

/** Every node:test call in `src`, in source order. */
export function findTests(src: string): TestCall[] {
  const toks = tokenize(src);
  // Matching brackets, by token index.
  const match = new Map<number, number>();
  const stack: number[] = [];
  for (let k = 0; k < toks.length; k++) {
    const tk = toks[k]!;
    if (tk.t !== 'p') continue;
    if (tk.v === '(' || tk.v === '[' || tk.v === '{') stack.push(k);
    else if (tk.v === ')' || tk.v === ']' || tk.v === '}') {
      const open = stack.pop();
      if (open !== undefined) {
        match.set(open, k);
        match.set(k, open);
      }
    }
  }
  const lineStarts = [0];
  for (let k = 0; k < src.length; k++) if (src[k] === '\n') lineStarts.push(k + 1);
  const lineOf = (off: number): number => {
    let lo = 0;
    let hi = lineStarts.length - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (lineStarts[mid]! <= off) lo = mid;
      else hi = mid - 1;
    }
    return lo + 1;
  };
  const colOf = (off: number): number => off - lineStarts[lineOf(off) - 1]! + 1;
  const isP = (k: number, v: string): boolean => toks[k]?.t === 'p' && (toks[k] as { v: string }).v === v;

  // Loops: `for (…) …` and `while (…) …` statements, and `<array>.forEach(…)` / `.map(…)` calls.
  const loops: Array<{ s: number; e: number }> = [];
  for (let k = 0; k < toks.length; k++) {
    const tk = toks[k]!;
    if (tk.t === 'id' && (tk.v === 'for' || tk.v === 'while') && isP(k + 1, '(') && !isP(k - 1, '.')) {
      const close = match.get(k + 1);
      if (close === undefined) continue;
      let end: number;
      if (isP(close + 1, '{')) end = match.get(close + 1) ?? close;
      else {
        // One statement: up to the first `;` at this depth, or the end of the call that starts it.
        let j = close + 1;
        while (j < toks.length && !isP(j, ';') && !isP(j, '}')) {
          const m = match.get(j);
          if (m !== undefined && m > j) j = m;
          if (isP(j, ')') && !isP(j + 1, '.') && !isP(j + 1, '(')) break;
          j++;
        }
        end = Math.min(j, toks.length - 1);
      }
      loops.push({ s: tk.s, e: toks[end]!.e });
    }
    if (tk.t === 'id' && (tk.v === 'forEach' || tk.v === 'map') && isP(k - 1, '.') && isP(k + 1, '(')) {
      const close = match.get(k + 1);
      if (close === undefined) continue;
      const recv = k - 2;
      const opener = isP(recv, ']') || isP(recv, ')') ? match.get(recv) : toks[recv]?.t === 'id' ? recv : undefined;
      loops.push({ s: toks[opener ?? k]!.s, e: toks[close]!.e });
    }
  }

  const calls: TestCall[] = [];
  for (let k = 0; k < toks.length; k++) {
    if (!isP(k, '(')) continue;
    // The callee: identifiers joined by dots, ending right before this parenthesis.
    const ids: number[] = [];
    let j = k - 1;
    while (toks[j]?.t === 'id') {
      ids.unshift(j);
      if (isP(j - 1, '.') && toks[j - 2]?.t === 'id') j -= 2;
      else break;
    }
    if (ids.length === 0) continue;
    const first = ids[0]!;
    if (isP(first - 1, '.')) continue; // `a.b().test(` or `x?.[0].test(`: not a test call
    const prev = toks[first - 1];
    if (prev?.t === 'id' && (prev.v === 'function' || prev.v === 'new' || prev.v === 'class')) continue;
    const names = ids.map((x) => (toks[x] as { v: string }).v);
    let kind: TestCall['kind'] | null = null;
    let subtest = false;
    if (names.length <= 2 && (BASE_TEST.has(names[0]!) || BASE_SUITE.has(names[0]!)) && (names.length === 1 || MODIFIERS.has(names[1]!))) {
      kind = BASE_TEST.has(names[0]!) ? 'test' : 'suite';
    } else if (names.length === 2 && names[1] === 'test') {
      kind = 'test';
      subtest = true;
    }
    if (!kind) continue;
    const close = match.get(k);
    if (close === undefined) continue;
    // `test(a, b) { … }` is a method being defined, not called.
    if (isP(close + 1, '{')) continue;
    // The first argument: up to the first comma at this depth.
    let argEnd = k + 1;
    while (argEnd < close && !isP(argEnd, ',')) {
      const m = match.get(argEnd);
      argEnd = m !== undefined && m > argEnd ? m + 1 : argEnd + 1;
    }
    const argToks = toks.slice(k + 1, argEnd);
    const literal = argToks.length === 1 ? argToks[0]! : null;
    // A subtest is `t.test('name', fn)`: a literal name and a second argument. `RE.test(line)` is neither.
    if (subtest && (argEnd >= close || !literal || (literal.t !== 'str' && literal.t !== 'tpl'))) continue;
    let name: string | null = null;
    let namePattern: string | null = null;
    if (literal?.t === 'str') {
      name = literal.v;
      namePattern = escapeRe(name);
    } else if (literal?.t === 'tpl') {
      if (literal.parts.length === 1) {
        name = literal.parts[0]!;
        namePattern = escapeRe(name);
      } else if (literal.parts.length === 2) {
        namePattern = literal.parts.map(escapeRe).join('.*');
      }
      // Two holes or more: unknown. `^a.*a.*…b$` backtracks exponentially on a name it misses, and the name is the
      // worker's: 25 holes and a 36-character name held the daemon's event loop for 5 s, about 3.3 times longer for
      // each character more. An unknown name matches any result, and the file runs unfiltered (namePatternFor).
    }
    const start = toks[ids[0]!]!.s;
    const end = toks[close]!.e;
    const argSrcEnd = argEnd < close ? toks[argEnd]!.s : toks[close]!.s;
    calls.push({
      kind,
      callee: names.join('.'),
      line: lineOf(start),
      cols: ids.map((x) => colOf(toks[x]!.s)),
      endLine: lineOf(end - 1),
      nameSrc: argToks.length ? src.slice(toks[k + 1]!.s, argSrcEnd).trim() : '',
      name,
      namePattern,
      parent: null,
      body: src.slice(argSrcEnd, end),
      loop: null,
      start,
      end,
    });
  }
  // Parents: the innermost call that contains this one. Calls are in source order, so a stack of open calls does it.
  const open: number[] = [];
  for (let k = 0; k < calls.length; k++) {
    const c = calls[k]!;
    while (open.length && calls[open[open.length - 1]!]!.end <= c.start) open.pop();
    c.parent = open.length ? open[open.length - 1]! : null;
    open.push(k);
  }
  for (const c of calls) {
    const floor = c.parent === null ? -1 : calls[c.parent]!.start;
    let best: { s: number; e: number } | null = null;
    for (const l of loops) {
      if (l.s <= c.start && c.end <= l.e && l.s > floor && (!best || l.s >= best.s)) best = l;
    }
    if (best) c.loop = { startLine: lineOf(best.s), endLine: lineOf(best.e - 1) };
  }
  return calls;
}

/** The changed lines of the new side of a unified diff with no context (`git diff -U0`), and the deletions between lines. */
export interface ChangedLines {
  /** New-side lines that were added or rewritten. */
  lines: Set<number>;
  /** A deletion with nothing added in its place, after new-side line `n` (0: at the top). */
  deletedAfter: number[];
}

export function changedLinesOf(diff: string): ChangedLines {
  const lines = new Set<number>();
  const deletedAfter: number[] = [];
  for (const m of diff.matchAll(/^@@ -\d+(?:,(\d+))? \+(\d+)(?:,(\d+))? @@/gm)) {
    const start = Number(m[2]);
    const count = m[3] === undefined ? 1 : Number(m[3]);
    if (count === 0) deletedAfter.push(start);
    for (let l = start; l < start + count; l++) lines.add(l);
  }
  return { lines, deletedAfter };
}

/** Every line of a file that is new as a whole. */
export function allLines(src: string): ChangedLines {
  const count = src === '' ? 0 : src.split('\n').length - (src.endsWith('\n') ? 1 : 0);
  return { lines: new Set(Array.from({ length: count }, (_v, k) => k + 1)), deletedAfter: [] };
}

export interface ChangedTest {
  call: TestCall;
  index: number;
  /** `added`: no test of this name was there; `renamed`: one with the same body under another name was; `changed`: it was, and is different. */
  change: 'added' | 'changed' | 'renamed';
}

/** The full name of a call as its source writes it: the first arguments of its ancestors and its own, raw. */
function rawPath(calls: TestCall[], k: number): string {
  const parts: string[] = [];
  for (let c: number | null = k; c !== null; c = calls[c]!.parent) parts.unshift(calls[c]!.nameSrc);
  return parts.join('\u0000');
}

/**
 * The tests (not describes) of `after` that the change touches, and how many changed lines are in no test or
 * describe at all. `before` is the file at the base, or null when the file is new there.
 */
export function changedTests(before: string | null, after: string, changed: ChangedLines): { tests: ChangedTest[]; unattributed: number } {
  const calls = findTests(after);
  const old = before === null ? [] : findTests(before);
  // Own lines: those of the call, less those of the calls inside it.
  const touched = calls.map((c, k) => {
    const inChild = (l: number): boolean => calls.some((d, m) => m !== k && d.parent === k && d.line <= l && l <= d.endLine);
    const own = (l: number): boolean => c.line <= l && l <= c.endLine && !inChild(l);
    if ([...changed.lines].some(own)) return true;
    // A deletion strictly inside the call, in its own lines.
    if (changed.deletedAfter.some((l) => own(l) && own(l + 1))) return true;
    // A loop that generates it, outside the call itself: its header or the table it walks.
    if (c.loop) {
      const lp = c.loop;
      // The loop's lines that are in no call inside it: a sibling test in the same loop is that test's own change.
      const inLoop = (l: number): boolean => lp.startLine <= l && l <= lp.endLine
        && !calls.some((d) => lp.startLine <= d.line && d.endLine <= lp.endLine && d.line <= l && l <= d.endLine);
      if ([...changed.lines].some(inLoop) || changed.deletedAfter.some((l) => inLoop(l) && inLoop(l + 1))) return true;
    }
    return false;
  });
  // A describe whose own lines changed (a hook, a shared fixture) changes every test under it, down to the next test.
  const viaSuite = (k: number): boolean => {
    for (let p = calls[k]!.parent; p !== null; p = calls[p]!.parent) {
      if (calls[p]!.kind !== 'suite') return false;
      if (touched[p]) return true;
    }
    return false;
  };
  const oldPaths = new Set(old.map((_c, k) => rawPath(old, k)));
  const tests: ChangedTest[] = [];
  calls.forEach((c, k) => {
    if (c.kind !== 'test' || !(touched[k] || viaSuite(k))) return;
    const change: ChangedTest['change'] = oldPaths.has(rawPath(calls, k))
      ? 'changed'
      : old.some((o) => o.kind === 'test' && o.body.trim() === c.body.trim() && o.nameSrc !== c.nameSrc) ? 'renamed' : 'added';
    tests.push({ call: c, index: k, change });
  });
  let unattributed = 0;
  const generating = calls.filter((c) => c.loop).map((c) => c.loop!);
  for (const l of changed.lines) {
    if (calls.some((c) => c.line <= l && l <= c.endLine)) continue;
    if (generating.some((lp) => lp.startLine <= l && l <= lp.endLine)) continue;
    unattributed++;
  }
  return { tests, unattributed };
}

/**
 * The --test-name-pattern that runs this call, anchored: its describes' names and its own, joined with a space as
 * node joins a full name. For a subtest it is the pattern of the outermost test around it — node runs a test's
 * subtests with it, and skips a subtest whose parent it skipped. null when a name on the way is built at run time
 * in a way no pattern can say (a variable): the caller then runs the file without a filter.
 */
export function namePatternFor(calls: TestCall[], index: number): string | null {
  let target = index;
  for (let p = calls[index]!.parent; p !== null; p = calls[p]!.parent) if (calls[p]!.kind === 'test') target = p;
  const parts: string[] = [];
  for (let c: number | null = target; c !== null; c = calls[c]!.parent) {
    const pat = calls[c]!.namePattern;
    if (pat === null) return null;
    parts.unshift(pat);
  }
  return `^${parts.join(' ')}$`;
}
